export const WORD_CATEGORY_OPTIONS = Object.entries(WORD_PACKS).map(([id, pack]) => ({
  id,
  label: pack.label,
  description: pack.description,
  count: new Set(pack.words).size,
}));

export const DEFAULT_WORD_CATEGORIES = WORD_CATEGORY_OPTIONS.map(({ id }) => id);

export function normalizeWordCategories(value) {
  const requested = Array.isArray(value) ? value : [];
  const valid = [...new Set(requested.filter((id) => Object.hasOwn(WORD_PACKS, id)))];
  return valid.length ? valid : [...DEFAULT_WORD_CATEGORIES];
}

export function wordsForCategories(value) {
  const categories = normalizeWordCategories(value);
  return [...new Set(categories.flatMap((id) => WORD_PACKS[id].words))];
}
